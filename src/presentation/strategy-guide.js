export function renderStrategyGuide(host) {
  const nodes = [];
  for (const section of SECTIONS) {
    const heading = document.createElement("h3"); heading.textContent = section.title; nodes.push(heading);
    for (const text of section.paragraphs) {
      const paragraph = document.createElement("p"); paragraph.textContent = text; nodes.push(paragraph);
    }
  }
  host.replaceChildren(...nodes);
}
